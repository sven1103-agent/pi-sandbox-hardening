#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# run-sandboxed.sh — launch a coding agent inside a Safehouse-derived policy.
#
# Project:  https://agent-safehouse.dev
# Part of:  pi-sandbox-hardening (see README.md)
#
# This is the integration point for every hardening step in this repo. It is the
# file that actually composes the policy and starts the agent, so it is worth
# reading even if you use a different agent or policy layout.
#
# Policy components (deliberately kept separate, so each is reviewable alone):
#   1) Base policy          ~/.config/sandbox-exec/agent.sb   (generated by safehouse)
#   2) Dynamic workdir      below in this script              (varies per launch)
#   3) Static local grants  ~/.config/sandbox-exec/grants.sb  (this repo's hardening)
#   4) Tmux/nvim (optional) ~/.safehouse-tmux.sb
#
# Why the hardening lives HERE and in grants.sb, rather than in the base policy:
#   - agent.sb is generated by safehouse; hand-editing it is lost on regeneration.
#   - grants.sb is concatenated AFTER the base policy, and SBPL is
#     last-match-wins, so a deny placed here overrides any broad base allow.
#
# Usage:
#   ./run-sandboxed.sh [--workdir=DIR] [agent args...]
#
# NOTE: the hardening blocks below are idempotent and marked so the
# scripts/apply-step-*.sh scripts can find, verify and roll them back.
# ---------------------------------------------------------------------------
set -euo pipefail

POLICY_DIR="${SANDBOX_POLICY_DIR:-$HOME/.config/sandbox-exec}"
BASE_POLICY="$POLICY_DIR/agent.sb"
GRANTS_FILE="$POLICY_DIR/grants.sb"
TMUX_PROFILE="$HOME/.safehouse-tmux.sb"

# The agent's own credential tree, and the binary to launch.
AGENT_DIR="${PI_AGENT_HOME:-$HOME/.agent}"
AGENT_KC="$AGENT_DIR/agent.keychain-db"
AGENT_BIN="${PI_BIN:-$(command -v pi || echo /opt/homebrew/bin/pi)}"

# --- Resolve workdir --------------------------------------------------------
workdir=""
passthrough_args=()

for arg in "$@"; do
  case "$arg" in
    --workdir=*) workdir="${arg#--workdir=}" ;;
    *)           passthrough_args+=("$arg") ;;
  esac
done

# Default workdir: current directory.
if [[ -z "$workdir" ]]; then
  workdir="$(pwd -P)"
fi

# Resolve to an absolute path (cd -P also resolves symlinks).
if [[ "$workdir" != /* ]]; then
  workdir="$(cd "$workdir" && pwd -P)"
fi

if [[ ! -d "$workdir" ]]; then
  echo "Error: workdir does not exist: $workdir" >&2
  exit 1
fi

# --- Build effective policy -------------------------------------------------
tmp_dir="${TMPDIR:-/tmp}"
tmp_policy="$(mktemp "${tmp_dir%/}/safehouse-policy.XXXXXX")"
# NOTE: no EXIT trap here. The script ends in `exec`, which REPLACES this shell,
# so an EXIT trap would never run. (Measured — this bit us once; see
# STEP-03b / TESTING.md.) The temp policy is left for the kernel to release.

# 1) Base policy, substituting the workdir placeholder.
#    safehouse emits the token __SAFEHOUSE_REPLACE_ME_WITH_WORK_DIR_DEFINE__ so a
#    wrapper can inject the workdir without regenerating the policy.
if [[ ! -f "$BASE_POLICY" ]]; then
  echo "Error: base policy not found: $BASE_POLICY" >&2
  echo "Generate one with:  safehouse --stdout > $BASE_POLICY" >&2
  exit 1
fi
sed "s|__SAFEHOUSE_REPLACE_ME_WITH_WORK_DIR_DEFINE__|(define WORK_DIR \"$workdir\")|g" \
  "$BASE_POLICY" > "$tmp_policy"

# 2) Dynamic workdir grant (must stay dynamic: the workdir varies per launch).
cat >> "$tmp_policy" <<WORKDIR_PROFILE

;; ---------------------------------------------------------------------------
;; Dynamic workdir grants — workdir: $workdir
;; ---------------------------------------------------------------------------
(allow file-read* file-write*
    (subpath "$workdir")
)
WORKDIR_PROFILE

# 3) Static local grants. This is where the hardening in this repo lives, and it
#    is appended LAST on purpose: last-match-wins means our denies override any
#    broad allow that came from the generated base policy.
if [[ -f "$GRANTS_FILE" ]]; then
  printf '\n;; --- Static grants (grants.sb) ---\n' >> "$tmp_policy"
  cat "$GRANTS_FILE" >> "$tmp_policy"
else
  echo "Warning: grants.sb not found at $GRANTS_FILE" >&2
fi

# 4) Optional tmux/nvim support.
if [[ -f "$TMUX_PROFILE" ]]; then
  printf '\n;; --- Tmux/Nvim support ---\n' >> "$tmp_policy"
  cat "$TMUX_PROFILE" >> "$tmp_policy"
fi

# --- Step 3b: unlock the agent's own keychain BEFORE entering the sandbox ----
# An unlock performed outside is inherited by the sandboxed process (verified).
# Inside the sandbox the login keychain is file-denied, so lookups fall through
# to the agent keychain — see grants.sb.
#
# Deliberately NOT done here: changing the keychain search list. That is set
# permanently (once) by scripts/setup-agent-keychain.sh. Two reasons:
#   1) a per-session restore cannot work — `exec` below replaces the shell, so an
#      EXIT/INT/TERM trap never fires (measured), and
#   2) a crash or SIGKILL would then leave the user's search list modified.
# The launcher touches nothing outside the sandbox; the fall-through does the work.
#
# The prompt is TTY-based: without a TTY it fails fast with rc 51 instead of
# hanging, so non-interactive launches warn rather than stall.
if [[ -f "$AGENT_KC" ]]; then
  if ! security show-keychain-info "$AGENT_KC" >/dev/null 2>&1; then
    printf 'Unlock agent keychain (%s): ' "$AGENT_KC" >&2
    security unlock-keychain "$AGENT_KC" || \
      echo "warning: agent keychain not unlocked; providers may fail" >&2
  fi
fi

# --- Step 5: sanitized environment ------------------------------------------
# Start from an EMPTY environment (`env -i`). Plain `env` only ADDS variables, so
# secrets exported in ~/.zshrc (SSH_AUTH_SOCK, *_TOKEN) reached the agent AND
# every subagent, regardless of the sandbox. Environment variables are not a
# filesystem concept, so NO SBPL grant or deny can constrain them.
#
# Every variable below was measured as required; everything else is dropped.
# Notably dropped: SSH_AUTH_SOCK (git-over-SSH uses the agent key with
# IdentitiesOnly=yes and needs no agent — verified) and any *_TOKEN.
env_args=(
  PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
  HOME="$HOME"
  USER="${USER:-$(id -un)}"
  LOGNAME="${LOGNAME:-$(id -un)}"
  SHELL="${SHELL:-/bin/zsh}"
  TMPDIR="${TMPDIR:-/tmp}"
  TERM="${TERM:-xterm-256color}"
  COLORTERM="${COLORTERM:-}"
  LANG="${LANG:-en_US.UTF-8}"
  EDITOR="${EDITOR:-}"
  VISUAL="${VISUAL:-}"
  TMUX="${TMUX:-}"
  # Step 2: agent-scoped identity. GIT_CONFIG_GLOBAL closes the ambient route to
  # the keychain via the host's global gitconfig (FINDINGS F12).
  GH_CONFIG_DIR="$AGENT_DIR/gh"
  GIT_CONFIG_GLOBAL="$AGENT_DIR/gitconfig"
  # Never read the host gitconfig: a host-level `credential.helper` is an
  # independent path to the login keychain.
  GIT_CONFIG_SYSTEM=/dev/null
)

# Pass through pi's own configuration variables only if already set.
for _opt in PI_OFFLINE PI_SKIP_VERSION_CHECK PI_TIMING PI_CODING_AGENT_DIR \
            PI_PACKAGE_DIR PI_SUBAGENT_PI_BINARY; do
  if [[ -n "${!_opt:-}" ]]; then
    env_args+=("$_opt=${!_opt}")
  fi
done
unset _opt

# Report dropped sensitive variables only when asked. Silent by default so it
# does not clutter every launch; the sanitization itself is unconditional.
if [[ -n "${PI_SANDBOX_VERBOSE:-}" ]]; then
  for _bad in SSH_AUTH_SOCK SSH_AGENT_PID; do
    if [[ -n "${!_bad:-}" ]]; then
      printf 'step-05: dropping inherited %s from the sandboxed environment\n' "$_bad" >&2
    fi
  done
fi
unset _bad

# --- Launch -----------------------------------------------------------------
# The `env -i` allowlist is expanded AFTER sandbox-exec, so the policy applies to
# the sanitized environment, not the ambient one.
#
# Keep every comment ABOVE this line: a '#' inside a backslash-continued command
# truncates the command and the agent never starts. (Measured — see STEP-02.)
exec sandbox-exec -f "$tmp_policy" env -i "${env_args[@]}" "$AGENT_BIN" \
  ${passthrough_args[@]+"${passthrough_args[@]}"}
